class ProfileViewModel(private val settingsRepo: SettingsRepository, private val privacy: PrivacyRepository) : ViewModel() {
    val settings: StateFlow<Settings?> = settingsRepo.settings.stateIn(viewModelScope, SharingStarted.WhileSubscribed(5_000), null)
    val storage = MutableStateFlow<StorageInfo?>(null)

    init {
        refreshStorage()
    }

    fun refreshStorage() {
        viewModelScope.launch { storage.value = privacy.storageInfo() }
    }

    fun setCyrillic(on: Boolean) = viewModelScope.launch { settingsRepo.setCyrillicOcr(on) }
    fun setTheme(mode: ThemeMode) = viewModelScope.launch { settingsRepo.setThemeMode(mode) }
    fun deleteGenerated(done: () -> Unit) = viewModelScope.launch { privacy.deleteGeneratedData(); done() }
    fun deleteEverything(done: () -> Unit) = viewModelScope.launch { privacy.deleteEverything(); refreshStorage(); done() }
}

@Composable
fun ProfileScreen(snackbar: SnackbarHostState) {
    val vm = appViewModel { ProfileViewModel(it.settings, it.privacy) }
    val settings by vm.settings.collectAsStateWithLifecycle()
    val storage by vm.storage.collectAsStateWithLifecycle()
    LifecycleResumeEffect(Unit) {
        vm.refreshStorage()
        onPauseOrDispose { }
    }
    var confirmGenerated by remember { mutableStateOf(false) }
    var confirmAll by remember { mutableStateOf(false) }
    val context = LocalContext.current
    val doneMessage = stringResource(R.string.profile_deleted)
    val scope = androidx.compose.runtime.rememberCoroutineScope()

    Column(
        Modifier.fillMaxSize().statusBarsPadding().verticalScroll(rememberScrollState()).padding(20.dp),
        verticalArrangement = Arrangement.spacedBy(14.dp),
    ) {
        Text(stringResource(R.string.profile_title), style = MaterialTheme.typography.headlineLarge)
        StudyCard {
            Row {
                Icon(AppIcons.Shield, null, Modifier.size(28.dp), tint = MaterialTheme.colorScheme.tertiary)
                Spacer(Modifier.width(12.dp))
                Column {
                    Text(stringResource(R.string.profile_offline_title), style = MaterialTheme.typography.titleMedium)
                    Text(stringResource(R.string.profile_offline_body), style = MaterialTheme.typography.bodySmall)
                }
            }
        }

        Overline(stringResource(R.string.profile_recognition))
        StudyCard {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Column(Modifier.weight(1f)) {
                    Text(stringResource(R.string.profile_cyrillic), style = MaterialTheme.typography.titleSmall)
                    Text(stringResource(R.string.profile_cyrillic_body), style = MaterialTheme.typography.bodySmall)
                }
                Switch(checked = settings?.cyrillicOcr == true, onCheckedChange = { vm.setCyrillic(it) })
            }
        }

        Overline(stringResource(R.string.profile_theme))
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            ThemeMode.entries.forEach { mode ->
                FilterChip(
                    selected = settings?.themeMode == mode,
                    onClick = { vm.setTheme(mode) },
                    label = {
                        Text(
                            stringResource(
                                when (mode) {
                                    ThemeMode.SYSTEM -> R.string.theme_system
                                    ThemeMode.LIGHT -> R.string.theme_light
                                    ThemeMode.DARK -> R.string.theme_dark
                                },
                            ),
                        )
                    },
                )
            }
        }

        Overline(stringResource(R.string.profile_storage))
        StudyCard {
            Text(
                storage?.let { stringResource(R.string.profile_storage_body, it.originals, Formatter.formatShortFileSize(context, it.bytes)) }
                    ?: "…",
                style = MaterialTheme.typography.bodyMedium,
            )
        }

        Overline(stringResource(R.string.profile_delete))
        StudyCard {
            Column(Modifier.fillMaxWidth()) {
                TextButton(onClick = { confirmGenerated = true }) { Text(stringResource(R.string.profile_delete_generated)) }
                TextButton(onClick = { confirmAll = true }) {
                    Text(stringResource(R.string.profile_delete_all), color = MaterialTheme.colorScheme.error)
                }
                Text(
                    stringResource(R.string.profile_delete_hint),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    modifier = Modifier.padding(horizontal = 12.dp),
                )
            }
        }
        Text(
            stringResource(R.string.profile_about),
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
    }

    if (confirmGenerated) {
        ConfirmDialog(
            title = stringResource(R.string.profile_delete_generated),
            body = stringResource(R.string.profile_delete_generated_body),
            confirmLabel = stringResource(R.string.action_delete),
            onConfirm = { vm.deleteGenerated { scope.launch { snackbar.showSnackbar(doneMessage) } } },
            onDismiss = { confirmGenerated = false },
        )
    }
    if (confirmAll) {
        ConfirmDialog(
            title = stringResource(R.string.profile_delete_all),
            body = stringResource(R.string.profile_delete_all_body),
            confirmLabel = stringResource(R.string.action_delete),
            onConfirm = { vm.deleteEverything { scope.launch { snackbar.showSnackbar(doneMessage) } } },
            onDismiss = { confirmAll = false },
        )
    }
}
